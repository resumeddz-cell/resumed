import json, hashlib, uuid
cur = json.load(open('supabase/curriculum_year1.json'))
def uid(path): return str(uuid.UUID(hashlib.md5(('resumed:' + path).encode()).hexdigest()))
def q(v):
    if v is None: return 'null'
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, int): return str(v)
    return "'" + str(v).replace("'", "''") + "'"
mods, less = [], []
def walk(ms, sem, parent, path):
    for i, m in enumerate(ms):
        p = f"{path}/{i+1}:{m['title']}"; mid = uid(p)
        mods.append((mid, 1, sem, parent, m['title'], m.get('description'), m.get('icon'), m.get('hero'), m.get('source_page'), i + 1))
        for j, l in enumerate(m['lessons']):
            less.append((uid(p + f"#{j+1}:{l['title']}"), mid, l.get('number') or f"{j+1:02d}", l['title'], l.get('icon'),
                         l.get('note'), j + 1, l.get('active', True)))
        walk(m['children'], sem, mid, p)
for s in cur: walk(s['modules'], s['semester'], None, f"Y1/{s['semester']}")
out = ["-- Year 1 curriculum transcribed from the source PDF (planner-compressed.pdf).",
       "-- Generated by tools/gen_seed.py. Safe to re-run: existing rows (and admin edits) are never overwritten.",
       "begin;"]
out.append("insert into public.modules (id, year, semester, parent_id, title, description, icon, hero, source_page, position) values")
out.append(",\n".join("(" + ", ".join(q(x) for x in m) + ")" for m in mods) + "\non conflict (id) do nothing;")
out.append("insert into public.lessons (id, module_id, number, title, icon, note, position, active) values")
out.append(",\n".join("(" + ", ".join(q(x) for x in l) + ")" for l in less) + "\non conflict (id) do nothing;")
out.append("commit;")
open('supabase/migrations/002_seed_year1_curriculum.sql', 'w').write("\n".join(out) + "\n")
print(len(mods), 'modules', len(less), 'lessons', sum(1 for l in less if l[-1]), 'active')
